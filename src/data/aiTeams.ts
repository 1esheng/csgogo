export const AI_TEAM_MAP: Record<string, AITeamSpec> = Object.fromEntries(AI_TEAMS.map((t) => [t.id, t]));

/** 取某档的队伍池；不足时按档位距离补齐，保证赛程永远能凑满。 */
/** 玩家联赛是 10 档，AI 队伍只分了 0-4 档：按比例映射过去。 */
export function aiTierFor(playerTier: number): number {
  return Math.max(0, Math.min(4, Math.round((playerTier * 4) / 9)));
}

export function teamsForTier(tier: number): AITeamSpec[] {
  const target = aiTierFor(tier);
  const exact = AI_TEAMS.filter((t) => t.tier === target);
  const nearby = AI_TEAMS
    .filter((t) => t.tier !== target)
    .sort((a, b) => Math.abs(a.tier - target) - Math.abs(b.tier - target));
  return [...exact, ...nearby];
}

export function pickAiMap(team: AITeamSpec, seed: number): MapId {
  if (!team.mapPref.length) return 'Mirage';
  return team.mapPref[Math.abs(seed) % team.mapPref.length];
}